"""Object storage for dataset files.

Two interchangeable backends: the local filesystem (development and tests) and any
S3-compatible service (Supabase Storage, Cloudflare R2, AWS S3) for production, where the
application host's own disk is ephemeral.

Storage keys are generated by the application from UUIDs. They never contain user input.
"""

from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import Settings, get_settings

_KEY_PATTERN = re.compile(r"^[a-z0-9]+(/[a-z0-9-]+)+\.[a-z0-9]+$")


class StorageError(RuntimeError):
    pass


class ObjectNotFoundError(StorageError):
    pass


def _check_key(key: str) -> str:
    if not _KEY_PATTERN.fullmatch(key):
        raise StorageError("invalid storage key")
    return key


class Storage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def check(self) -> None:
        """Raise `StorageError` when the backend is unreachable."""


class LocalStorage:
    def __init__(self, root: str):
        self._root = Path(root).resolve()
        self._root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self._root / _check_key(key)).resolve()
        if not path.is_relative_to(self._root):
            raise StorageError("invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as exc:
            raise ObjectNotFoundError(key) from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def check(self) -> None:
        if not self._root.is_dir():
            raise StorageError("local storage directory is missing")


class S3Storage:
    def __init__(self, settings: Settings):
        import boto3
        from botocore.config import Config

        self._bucket = settings.s3_bucket or ""
        self._client = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url,
            region_name=settings.s3_region,
            aws_access_key_id=settings.s3_access_key_id,
            aws_secret_access_key=settings.s3_secret_access_key,
            config=Config(
                signature_version="s3v4",
                s3={"addressing_style": "path"},
                retries={"max_attempts": 3, "mode": "standard"},
                connect_timeout=10,
                read_timeout=60,
                # Newer botocore sends CRC checksums by default, which several S3-compatible
                # services reject; only send them when the operation requires it.
                request_checksum_calculation="when_required",
                response_checksum_validation="when_required",
            ),
        )

    def put(self, key: str, data: bytes) -> None:
        from botocore.exceptions import BotoCoreError, ClientError

        try:
            self._client.put_object(
                Bucket=self._bucket, Key=_check_key(key), Body=data, ContentType="application/octet-stream"
            )
        except (BotoCoreError, ClientError) as exc:
            raise StorageError("could not store object") from exc

    def get(self, key: str) -> bytes:
        from botocore.exceptions import BotoCoreError, ClientError

        try:
            response = self._client.get_object(Bucket=self._bucket, Key=_check_key(key))
            return bytes(response["Body"].read())
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") in ("NoSuchKey", "404"):
                raise ObjectNotFoundError(key) from exc
            raise StorageError("could not read object") from exc
        except BotoCoreError as exc:
            raise StorageError("could not read object") from exc

    def delete(self, key: str) -> None:
        from botocore.exceptions import BotoCoreError, ClientError

        try:
            self._client.delete_object(Bucket=self._bucket, Key=_check_key(key))
        except (BotoCoreError, ClientError) as exc:
            raise StorageError("could not delete object") from exc

    def check(self) -> None:
        from botocore.exceptions import BotoCoreError, ClientError

        try:
            self._client.head_bucket(Bucket=self._bucket)
        except (BotoCoreError, ClientError) as exc:
            raise StorageError("object storage is unreachable") from exc


@lru_cache
def get_storage() -> Storage:
    settings = get_settings()
    if settings.storage_backend == "s3":
        return S3Storage(settings)
    return LocalStorage(settings.local_storage_dir)
